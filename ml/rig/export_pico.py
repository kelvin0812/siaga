"""
Exports the trained phase model as C++ headers for the Raspberry Pi Pico, so the siren can decide the phase on
the device itself, with no Wi-Fi or server.

Writes two generated headers into the output folder (default: ../siaga_pico next to this repo):
  phase_model.h     every decision tree as constant arrays, plus the calibration the model was trained with
  phase_selftest.h  real rig readings with the answers the Python predictor gave, which the Pico replays at boot

The hand-written C++ that walks the trees (phase_engine.h) lives with the sketch, not here. This file also holds
PortEngine, a line-by-line Python port of that C++, used by the tests to check the generated arrays and the logic
against the real LightGBM model and real rig rows before anything is flashed.

    python -m ml.rig.export_pico
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from ml.rig.export_app import APP_FIXTURE, MODEL_DIR, export_booster

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT.parent / "siaga_pico"
SELFTEST_CASE_LENGTHS = (160, 150)     # rows used from each fixture case: one crosses Phase 1 to 2, one Phase 3 to 4


def flatten_forest(model: dict) -> dict:
    """Concatenate every tree into shared arrays, with per-tree offsets (the layout phase_engine.h reads)."""
    feat, thr, left, right, leaf = [], [], [], [], []
    node_off, leaf_off = [0], [0]
    for tree in model["trees"]:
        feat += tree["f"]
        thr += tree["t"]
        left += tree["l"]
        right += tree["r"]
        leaf += tree["v"]
        node_off.append(len(feat))
        leaf_off.append(len(leaf))
    return {"num_trees": len(model["trees"]), "num_class": model["num_class"], "node_off": node_off, "leaf_off": leaf_off,
            "feat": feat, "thr": thr, "left": left, "right": right, "leaf": leaf}


def _fmt(values, per_line=8, as_double=False):
    items = [repr(float(v)) if as_double else str(int(v)) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "{\n  " + ",\n  ".join(lines) + "\n}"


def render_model_header(meta: dict, level: dict, others: dict) -> str:
    cal = meta["calibration"]
    out = [
        "// GENERATED by ml/rig/export_pico.py from backend/models/phase_model. Do not edit by hand.",
        "// Retrain with `python -m ml.rig.train`, then re-run `python -m ml.rig.export_pico` and re-flash.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct PhaseForest {",
        "  int numTrees;",
        "  const uint32_t* nodeOff;   // first question of each tree (one extra entry marks the end)",
        "  const uint32_t* leafOff;   // first score of each tree",
        "  const uint8_t* feat;       // which input each question looks at",
        "  const double* thr;         // the cut-off of each question (go left if the input is <= this)",
        "  const int16_t* left;       // next question if yes; negative means a score, number ~value",
        "  const int16_t* right;      // next question if no",
        "  const double* leaf;        // the scores",
        "};",
        "",
        "namespace phase_model {",
        f"static const double BASELINE_DIST_CM = {cal['baseline_dist_cm']!r};",
        f"static const double REST_ACCEL[3] = {{{', '.join(repr(float(v)) for v in cal['rest_accel'])}}};",
        f"static const double GYRO_BIAS[3] = {{{', '.join(repr(float(v)) for v in cal['gyro_bias'])}}};",
        f"static const double LEVEL_WEIGHT = {float(meta['level_weight'])!r};",
        f"static const int SMOOTHING = {int(meta['smoothing_readings'])};",
        f"static const int NUM_CLASS = {level['num_class']};",
        "",
    ]
    for name, forest in (("LEVEL", level), ("OTHERS", others)):
        out += [
            f"static const uint32_t {name}_NODE_OFF[] = {_fmt(forest['node_off'])};",
            f"static const uint32_t {name}_LEAF_OFF[] = {_fmt(forest['leaf_off'])};",
            f"static const uint8_t {name}_FEAT[] = {_fmt(forest['feat'], 24)};",
            f"static const double {name}_THR[] = {_fmt(forest['thr'], 6, True)};",
            f"static const int16_t {name}_LEFT[] = {_fmt(forest['left'], 16)};",
            f"static const int16_t {name}_RIGHT[] = {_fmt(forest['right'], 16)};",
            f"static const double {name}_LEAF[] = {_fmt(forest['leaf'], 6, True)};",
            f"static const PhaseForest {name} = {{ {forest['num_trees']}, {name}_NODE_OFF, {name}_LEAF_OFF, {name}_FEAT, "
            f"{name}_THR, {name}_LEFT, {name}_RIGHT, {name}_LEAF }};",
            "",
        ]
    out.append("}  // namespace phase_model")
    return "\n".join(out) + "\n"


def render_selftest_header(cases: list[dict]) -> str:
    rows, exp = [], []
    for c in cases:
        for r, e in zip(c["rows"], c["expected"]):
            rows.append("  {" + ", ".join(repr(float(v)) for v in (r["t"], r["dist"], r["flow"], r["soil"], *r["accel"], *r["gyro"])) + "}")
            if e is None:
                exp.append("  {0, {0, 0, 0, 0}}")
            else:
                exp.append(f"  {{{e['phase']}, {{{', '.join(repr(float(p)) for p in e['probs'])}}}}}")
    lens = ", ".join(str(len(c["rows"])) for c in cases)
    return "\n".join([
        "// GENERATED by ml/rig/export_pico.py. Real rig readings and the answers the Python model gave for them.",
        "// The Pico replays these at boot and prints SELFTEST PASS or SELFTEST FAIL.",
        "#pragma once",
        "",
        "struct SelfTestRow { double t, dist, flow, soil, ax, ay, az, gx, gy, gz; };",
        "struct SelfTestExpect { int phase; double p[4]; };   // phase 0 = the engine should not answer yet",
        f"static const int SELFTEST_CASES = {len(cases)};",
        f"static const int SELFTEST_LEN[] = {{{lens}}};",
        "static const SelfTestRow SELFTEST_ROWS[] = {",
        ",\n".join(rows),
        "};",
        "static const SelfTestExpect SELFTEST_EXPECT[] = {",
        ",\n".join(exp),
        "};",
        "",
    ])


# ---------------------------------------------------------------- Python port of phase_engine.h

def _median(values):
    s = sorted(values)
    n = len(s)
    return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2


class _Window:
    def __init__(self, n):
        self.n, self.buf, self.count = n, [0.0] * n, 0

    def push(self, x):
        self.buf[self.count % self.n] = x
        self.count += 1

    def values(self):
        return self.buf[: min(self.count, self.n)]


def forest_proba(forest: dict, x: list[float]) -> list[float]:
    """The same walk as treeEval()/forestProba() in phase_engine.h, on the flattened arrays."""
    raw = [0.0] * 4
    for t in range(forest["num_trees"]):
        no, lo = forest["node_off"][t], forest["leaf_off"][t]
        if forest["node_off"][t + 1] == no:
            val = forest["leaf"][lo]
        else:
            n = 0
            while True:
                nxt = forest["left"][no + n] if x[forest["feat"][no + n]] <= forest["thr"][no + n] else forest["right"][no + n]
                if nxt < 0:
                    val = forest["leaf"][lo + (~nxt)]
                    break
                n = nxt
        raw[t % 4] += val
    m = max(raw)
    e = [math.exp(r - m) for r in raw]
    s = sum(e)
    return [v / s for v in e]


class PortEngine:
    def __init__(self, meta: dict, level: dict, others: dict):
        cal = meta["calibration"]
        self.level, self.others = level, others
        self.baseline, self.rest, self.bias = cal["baseline_dist_cm"], cal["rest_accel"], cal["gyro_bias"]
        self.w, self.smooth = float(meta["level_weight"]), int(meta["smoothing_readings"])
        self.dists, self.flows, self.soils = _Window(10), _Window(10), _Window(10)
        self.tilts, self.gyros, self.recent = _Window(5), _Window(10), _Window(self.smooth)
        self.lv, self.lv_ok, self.times, self.n = [0.0] * 21, [False] * 21, [0.0] * 21, 0

    def update(self, t, dist, flow, soil, ax, ay, az, gx, gy, gz):
        if dist <= 0:
            return None
        self.dists.push(dist); self.flows.push(flow); self.soils.push(soil)
        have_level = self.dists.count >= 5
        level = _median(self.dists.values()) if have_level else 0.0
        p = self.n % 21
        self.lv[p], self.lv_ok[p], self.times[p] = level, have_level, t
        self.n += 1
        rest_norm = math.sqrt(sum(v * v for v in self.rest))
        a_norm = math.sqrt(ax * ax + ay * ay + az * az)
        cos = max(-1.0, min(1.0, (ax * self.rest[0] + ay * self.rest[1] + az * self.rest[2]) / (a_norm * rest_norm)))
        self.tilts.push(math.degrees(math.acos(cos)))
        self.gyros.push(math.sqrt((gx - self.bias[0]) ** 2 + (gy - self.bias[1]) ** 2 + (gz - self.bias[2]) ** 2))
        have_rate, rate = False, 0.0
        if have_level and self.n > 20:
            o = self.n % 21
            if self.lv_ok[o]:
                rate, have_rate = -(level - self.lv[o]) / ((t - self.times[o]) / 60.0), True
        if not (have_level and have_rate and self.flows.count >= 5 and self.soils.count >= 5 and self.tilts.count >= 3 and self.gyros.count >= 3):
            return None
        xl = [self.baseline - level, rate]
        xo = [_median(self.flows.values()), _median(self.soils.values()), _median(self.tilts.values()), max(self.gyros.values())]
        pl, po = forest_proba(self.level, xl), forest_proba(self.others, xo)
        prob = [self.w * a + (1 - self.w) * b for a, b in zip(pl, po)]
        raw = 0
        for i in range(1, 4):
            if prob[i] > prob[raw]:
                raw = i
        self.recent.push(raw)
        window = self.recent.values()
        best, best_count = 0, -1
        for k in range(4):
            c = window.count(k)
            if c > best_count:
                best, best_count = k, c
        return best + 1, raw + 1, prob


def load_parts():
    meta = json.loads((MODEL_DIR / "phase_model.json").read_text(encoding="utf-8"))
    level = flatten_forest(export_booster(MODEL_DIR / "level_model.txt"))
    others = flatten_forest(export_booster(MODEL_DIR / "others_model.txt"))
    return meta, level, others


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    meta, level, others = load_parts()
    fixture = json.loads(APP_FIXTURE.read_text(encoding="utf-8"))["cases"]
    cases = [{"rows": c["rows"][:n], "expected": c["expected"][:n]} for c, n in zip(fixture, SELFTEST_CASE_LENGTHS)]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "phase_model.h").write_text(render_model_header(meta, level, others), encoding="utf-8")
    (args.out / "phase_selftest.h").write_text(render_selftest_header(cases), encoding="utf-8")
    size = sum(f.stat().st_size for f in args.out.glob("phase_*.h")) // 1024
    print(f"wrote phase_model.h and phase_selftest.h to {args.out} ({size} KB of source)")


if __name__ == "__main__":
    main()
